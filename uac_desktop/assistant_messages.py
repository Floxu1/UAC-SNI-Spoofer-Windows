from __future__ import annotations

import re


LRI = "\u2066"
PDI = "\u2069"
_LTR_RUN = re.compile(
    r"[A-Za-z0-9][A-Za-z0-9._:/\\?#%&=+\-@\[\](){}]*"
    r"(?:[ \t]+[A-Za-z0-9][A-Za-z0-9._:/\\?#%&=+\-@\[\](){}]*)*"
)
_ISOLATED = re.compile(f"({LRI}.*?{PDI})", re.DOTALL)


def ltr(value: object) -> str:
    return f"{LRI}{value}{PDI}"


def mixed(value: object) -> str:
    text = str(value or "").strip()
    if not any("\u0600" <= char <= "\u06ff" for char in text):
        return ltr(text)
    parts = _ISOLATED.split(text)
    return "".join(
        part if part.startswith(LRI) and part.endswith(PDI)
        else _LTR_RUN.sub(lambda match: ltr(match.group(0)), part)
        for part in parts
    )


