def message(key: str, **values: object) -> str:
    template = MESSAGES.get(key, MESSAGES["normal"])
    safe_values = {name: str(value) for name, value in values.items()}
    try:
        return template.format(**safe_values)
    except (KeyError, ValueError):
        return template
